-- Additive SQL Server migration for authenticated admin and catalog management.
-- Run only after backup and DBA approval. This script does not drop existing data.
-- The admin account is promoted only when the explicitly configured email exists.

IF COL_LENGTH(N'dbo.NGUOIDUNG', N'VaiTro') IS NULL
BEGIN
  ALTER TABLE dbo.NGUOIDUNG
    ADD VaiTro NVARCHAR(20) NOT NULL
      CONSTRAINT DF_NGUOIDUNG_VaiTro DEFAULT (N'CUSTOMER') WITH VALUES;
END;
GO

IF NOT EXISTS (
  SELECT 1 FROM sys.check_constraints WHERE name = N'CK_NGUOIDUNG_VaiTro'
)
BEGIN
  ALTER TABLE dbo.NGUOIDUNG WITH CHECK
    ADD CONSTRAINT CK_NGUOIDUNG_VaiTro CHECK (VaiTro IN (N'CUSTOMER', N'ADMIN'));
END;
GO

IF COL_LENGTH(N'dbo.TOUR', N'Slug') IS NULL
  ALTER TABLE dbo.TOUR ADD Slug VARCHAR(255) NULL;
IF COL_LENGTH(N'dbo.TOUR', N'Duration') IS NULL
  ALTER TABLE dbo.TOUR ADD Duration NVARCHAR(50) NULL;
IF COL_LENGTH(N'dbo.TOUR', N'Departure') IS NULL
  ALTER TABLE dbo.TOUR ADD Departure NVARCHAR(255) NULL;
IF COL_LENGTH(N'dbo.TOUR', N'Transport') IS NULL
  ALTER TABLE dbo.TOUR ADD Transport NVARCHAR(255) NULL;
IF COL_LENGTH(N'dbo.TOUR', N'GiaGoc') IS NULL
  ALTER TABLE dbo.TOUR ADD GiaGoc DECIMAL(18,2) NULL;
IF COL_LENGTH(N'dbo.TOUR', N'FlashSale') IS NULL
  ALTER TABLE dbo.TOUR ADD FlashSale BIT NOT NULL
    CONSTRAINT DF_TOUR_FlashSale DEFAULT (0) WITH VALUES;
GO

IF NOT EXISTS (
  SELECT 1 FROM sys.indexes
  WHERE object_id = OBJECT_ID(N'dbo.TOUR') AND name = N'UX_TOUR_Slug'
)
  CREATE UNIQUE INDEX UX_TOUR_Slug ON dbo.TOUR(Slug) WHERE Slug IS NOT NULL;
GO

IF COL_LENGTH(N'dbo.LICH_TRINH_DETAIL', N'ThuTuTrongNgay') IS NULL
  ALTER TABLE dbo.LICH_TRINH_DETAIL ADD ThuTuTrongNgay INT NULL;
IF COL_LENGTH(N'dbo.LICH_TRINH_DETAIL', N'LoaiHoatDong') IS NULL
  ALTER TABLE dbo.LICH_TRINH_DETAIL ADD LoaiHoatDong NVARCHAR(30) NULL;
IF COL_LENGTH(N'dbo.LICH_TRINH_DETAIL', N'DiaDiem') IS NULL
  ALTER TABLE dbo.LICH_TRINH_DETAIL ADD DiaDiem NVARCHAR(180) NULL;
IF COL_LENGTH(N'dbo.LICH_TRINH_DETAIL', N'GioBatDau') IS NULL
  ALTER TABLE dbo.LICH_TRINH_DETAIL ADD GioBatDau CHAR(5) NULL;
GO

IF OBJECT_ID(N'dbo.API_TOUR_COST_ITEM', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.API_TOUR_COST_ITEM (
    MaKhoanChi INT IDENTITY(1,1) NOT NULL,
    MaTour INT NOT NULL,
    DanhMuc NVARCHAR(40) NOT NULL,
    TenKhoanChi NVARCHAR(150) NOT NULL,
    GhiChu NVARCHAR(2000) NOT NULL CONSTRAINT DF_API_TOUR_COST_GhiChu DEFAULT (N''),
    ChiPhiMoiNguoi BIGINT NOT NULL,
    CONSTRAINT PK_API_TOUR_COST_ITEM PRIMARY KEY CLUSTERED (MaKhoanChi),
    CONSTRAINT FK_API_TOUR_COST_TOUR FOREIGN KEY (MaTour) REFERENCES dbo.TOUR(MaTour),
    CONSTRAINT CK_API_TOUR_COST_Amount CHECK (ChiPhiMoiNguoi >= 0)
  );
  CREATE INDEX IX_API_TOUR_COST_TOUR ON dbo.API_TOUR_COST_ITEM(MaTour, MaKhoanChi);
END;
GO

IF COL_LENGTH(N'dbo.NGUOIDUNG', N'Email') IS NOT NULL
BEGIN
  UPDATE dbo.NGUOIDUNG
  SET VaiTro = N'ADMIN'
  WHERE LOWER(Email) = N'admin@deltatravel.vn';
END;
GO
